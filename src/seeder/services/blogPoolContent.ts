/** Speciality → 3 pool topics (unknown speciality → general pool). */
export function poolTopicsFor(speciality: string): DoctorPoolTopic[] {
  return POOL_BY_SPECIALITY[speciality.trim()] ?? FALLBACK_POOL;
}

export interface DoctorPoolSeedInput {
  slug: string;
  title: string;
  excerpt: string;
  content: string;
  coverGradient: string;
  coverSymbol: string;
  category: string;
  tags: string[];
  authorName: string;
  publishedAt: Date;
}

/**
 * Build 3 ready-to-store seeds for one doctor.
 * `daysAgoBase` staggers publish dates so profiles look naturally grown.
 */
export function buildDoctorPoolSeeds(
  doctor: { username: string; name: string; speciality: string },
  daysAgoBase = 0,
): DoctorPoolSeedInput[] {
  return poolTopicsFor(doctor.speciality).map((t, i) => ({
    slug: `${t.slugBase}-${doctor.username}`.slice(0, 80),
    title: t.title,
    excerpt: t.excerpt,
    content: t.content,
    coverGradient: t.coverGradient,
    coverSymbol: t.coverSymbol,
    category: t.category,
    tags: t.tags,
    authorName: doctor.name,
    publishedAt: new Date(Date.now() - (daysAgoBase + i * 12 + 3) * 24 * 60 * 60 * 1000),
  }));
}
