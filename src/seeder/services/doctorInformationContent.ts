export interface TimelineDoctorInput {
  degree: string;
  speciality: string;
  startedYear?: number | null;
  firstChamberThana?: string | null;
}

/**
 * 4–5 timeline entries derived from the doctor's own degree / speciality / startedYear.
 * Index rotates colleges & hospitals so neighbouring doctors don't read identically.
 */
export function buildTimelineForDoctor(doctor: TimelineDoctorInput, index: number): TimelineItem[] {
  const start = doctor.startedYear ?? 2010;
  const mbbsYear = start - 7;
  const pgYear = mbbsYear + 6;

  const postgrad = doctor.degree
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean)
    .slice(1, 3)
    .join(', ');

  const timeline: TimelineItem[] = [
    { year: toBnYear(mbbsYear), title: `এমবিবিএস, ${MBBS_COLLEGES[index % MBBS_COLLEGES.length]}` },
    {
      year: toBnYear(pgYear),
      title: `${postgrad || 'উচ্চতর ডিগ্রি'}, ${PG_INSTITUTES[index % PG_INSTITUTES.length]}`,
    },
    {
      year: toBnYear(start + 2),
      title: `${doctor.speciality} কনসালট্যান্ট, নীলফামারী সদর হাসপাতাল`,
    },
    {
      year: toBnYear(start + 6),
      title: `ব্যক্তিগত চেম্বার প্রতিষ্ঠা, ${doctor.firstChamberThana || 'নীলফামারী'}`,
    },
  ];

  // Every 3rd doctor gets a 5th milestone so timelines vary in length.
  if (index % 3 === 0) {
    timeline.splice(3, 0, {
      year: toBnYear(pgYear + 2),
      title: `বিশেষ প্রশিক্ষণ, ${doctor.speciality} — ঢাকা`,
    });
  }

  return timeline;
}
